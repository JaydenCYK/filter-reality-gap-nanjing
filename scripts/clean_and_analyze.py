def load_records(path):
    raw = open(path, encoding="utf-8").read().splitlines()
    records = []
    for ln in raw:
        s = ln.strip()
        if not s:
            continue
        if DATE_RE.search(s):
            continue
        if s in SECTION_HEADERS:
            continue
        if s in ("点赞","举报","1","2","3"):
            continue
        if s.startswith("举报") and len(s) < 6:
            continue
        if s == "关键词：南京照骗" or s == "关键词：南京旅游踩雷":
            continue
        # 剔除纯百科/官方描述（含多个标志词且无明显情感词）
        records.append(s)
    # 精确去重（保留顺序）
    seen = set(); out = []
    for r in records:
        key = re.sub(r"\s+", "", r)[:120]
        if key in seen:
            continue
        seen.add(key); out.append(r)
    return out

def sentiment(r):
    p = sum(1 for w in POS if w in r)
    n = sum(1 for w in NEG if w in r)
    if n == 0 and p == 0:
        return "中性"
    if p > n:
        return "正面"
    if n > p:
        return "负面"
    return "中性"

def main():
    recs = load_records(SRC)
    N = len(recs)
    # 情感统计
    sent = {"正面":0,"中性":0,"负面":0}
    for r in recs:
        sent[sentiment(r)] += 1
    # 要素词频（每条记录内每个要素去重计1次）
    elem = {k:0 for k in ELEMENTS}
    for r in recs:
        for k, kws in ELEMENTS.items():
            if any(w in r for w in kws):
                elem[k] += 1
    # 负面因子命中条数
    neg_hit = sum(1 for r in recs if any(w in r for w in NEGATIVE_MARKERS))
    stats = {
        "N_unique": N,
        "sentiment": sent,
        "sentiment_pct": {k: round(v/N*100,1) for k,v in sent.items()},
        "element_freq": elem,
        "element_pct": {k: round(v/N*100,1) for k,v in elem.items()},
        "negative_marker_hits": neg_hit,
    }
    out = os.path.join(OUTDIR, "ugc_stats.json")
    json.dump(stats, open(out,"w",encoding="utf-8"), ensure_ascii=False, indent=2)
    print("去重后样本 N =", N)
    print("情感分布:", sent, stats["sentiment_pct"])
    print("要素频次:")
    for k in sorted(elem, key=elem.get, reverse=True):
        print(f"  {k}: {elem[k]}  ({stats['element_pct'][k]}%)")
    print("含负面因子条数:", neg_hit)
    print("saved:", out)

if __name__ == "__main__":
    main()
